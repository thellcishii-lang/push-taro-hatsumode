let baaAudio: HTMLAudioElement | null = null;

function getBaaAudio(): HTMLAudioElement | null {
  try {
    if (!baaAudio) {
      baaAudio = new Audio(SHEEP_BAA_DATA_URI);
      // 境内に配慮して、音量は控えめにしておく
      baaAudio.volume = 0.6;
    }
    return baaAudio;
  } catch {
    return null;
  }
}

/** ユーザーのタップの中で呼んで、音源を先読みしておく（iOS 対策）。 */
export function primeSheepBaa() {
  const audio = getBaaAudio();
  if (!audio) return;
  try {
    audio.load();
  } catch {
    // 先読みできなくても本再生のときに再試行する
  }
}

/** 羊の鳴き声を鳴らす。鳴らせない環境では何もしない。 */
export function playSheepBaa() {
  const audio = getBaaAudio();
  if (!audio) return;
  try {
    audio.currentTime = 0;
    void audio.play().catch(() => {});
  } catch {
    // 音が出なくても画面の流れは止めない
  }
}
